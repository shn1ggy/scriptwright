import os from 'os';
import path from 'path';
import { startHarness, sleep } from './util.mjs';
const out = (n) => path.join(os.tmpdir(), `sw3-${n}.png`);
const h = await startHarness();
const { page } = h;
const app = (fn, ...a) => page.evaluate(fn, ...a);
const sel = (t) => app((t) => { const ed = window.__app.editor; for (let i = 0; i < ed.lines.length; i++) { const c = ed.lines[i].text.indexOf(t); if (c >= 0) { ed.setSelection({ anchor: { line: i, ch: c }, head: { line: i, ch: c + t.length } }, { scroll: 'center' }); return; } } }, t);
await sel('lamp turns'); await app(() => window.__app.annotations.highlight('yellow'));
await sel('She hums something'); await app(() => window.__app.annotations.highlight('pink'));
await sel("Who's there?"); await app(() => window.__app.annotations.addComment('Make this scarier — she should already know.', window.__app.annotations.selectionAnchor()));
await sel('One more night. Just one more.');
await page.keyboard.press('Alt+A');
await page.waitForSelector('.rewrite-dialog textarea');
await page.fill('.rewrite-dialog textarea', 'Just this night.\nThen never again.');
await sleep(150);
await page.screenshot({ path: out('rewrite') });
await page.click('.rewrite-dialog .btn:has-text("Use this version")');
await page.keyboard.press('Escape');
await app(() => { window.__app.showRightTab('comments'); window.__app.editor.scrollToLine(10, 'top'); });
await sleep(300);
await page.screenshot({ path: out('review') });
await page.keyboard.press('Control+Shift+D'); await page.waitForSelector('.dialog input'); await page.keyboard.type('Read-through draft'); await page.keyboard.press('Enter'); await sleep(300);
await app(() => { const a = window.__app; const sc = a.scenes.filter((s) => s.kind === 'scene'); a.moveScene(sc[2], sc[0], false); });
await sel("The boat's gone."); await page.keyboard.type('The boat is gone!');
await app(() => window.__app.showRightTab('history')); await sleep(200);
await page.click('.rv-item:has-text("Read-through") .btn:has-text("Preview")');
await page.waitForSelector('.compare-dialog'); await sleep(200);
await page.screenshot({ path: out('compare') });
console.log(JSON.stringify(h.errors.filter((e) => !e.includes('404'))));
await h.stop();
