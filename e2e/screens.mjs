// Screenshots of the main surfaces for visual review.
import path from 'path';
import os from 'os';
import { startHarness, sleep } from './util.mjs';
const out = path.join(os.tmpdir(), 'sw-');
const h = await startHarness();
const { page } = h;
await sleep(800);
const app = (fn, ...a) => page.evaluate(fn, ...a);
await app(() => window.__app.showRightTab('scene'));
await app(() => { const a = window.__app; const s = a.scenes.find((x) => x.kind === 'scene'); a.goToScene(s); });
await sleep(200);
await page.screenshot({ path: out + 's-right.png' });
await page.keyboard.press('Control+F');
await page.keyboard.type('lisa');
await sleep(200);
await page.screenshot({ path: out + 's-find.png' });
await page.keyboard.press('Escape');
await page.keyboard.press('Control+K');
await sleep(200);
await page.screenshot({ path: out + 's-palette.png' });
await page.keyboard.press('Escape');
await page.keyboard.press('Control+P');
await sleep(200);
await page.screenshot({ path: out + 's-settings.png' });
await page.click('.settings nav .row:has-text("Appearance")');
await page.selectOption('.settings select[aria-label="Theme"]', 'light');
await sleep(200);
await page.screenshot({ path: out + 's-light-settings.png' });
await page.keyboard.press('Escape');
await sleep(100);
await page.screenshot({ path: out + 's-light.png' });
await page.click('.tab:has-text("Dialogue")');
await sleep(200);
await page.screenshot({ path: out + 's-dialogue.png' });
console.log(JSON.stringify(h.errors.filter((e) => !e.includes('404'))));
await h.stop();
