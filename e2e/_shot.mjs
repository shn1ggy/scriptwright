import { startHarness, sleep } from './util.mjs';
const h = await startHarness();
const { page } = h;
const out = process.argv[2];
await page.setViewportSize({ width: 1280, height: 760 });
await page.evaluate(() => window.__app.run('view.toggleRightPane'));
await sleep(400);
await page.screenshot({ path: out + '/both.png' });
await page.evaluate(() => { window.__app.run('view.toggleRightPane'); window.__app.run('view.toggleLeftPane'); });
await sleep(400);
await page.screenshot({ path: out + '/none.png' });
await page.evaluate(() => { window.__app.run('view.toggleLeftPane'); window.__app.openPanel('export'); });
await sleep(1500);
await page.hover('.preview-dim input');
await sleep(200);
await page.screenshot({ path: out + '/export.png', clip: { x: 0, y: 70, width: 1280, height: 60 } });
await page.screenshot({ path: out + '/export-full.png' });
await h.stop();
